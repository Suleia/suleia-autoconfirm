import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

test('Operations Center exposes Pedidos, Incidencias and truthful Control de gasto with no write controls', () => {
  const html = fs.readFileSync(new URL('./index.html', import.meta.url), 'utf8');
  const script = fs.readFileSync(new URL('./app.js', import.meta.url), 'utf8');
  const css = fs.readFileSync(new URL('./styles.css', import.meta.url), 'utf8');
  const loginCss = fs.readFileSync(new URL('./login.css', import.meta.url), 'utf8');
  assert.equal((html.match(/class="nav-item/g) || []).length, 3);
  assert.match(html, />Pedidos</);
  assert.match(html, />Incidencias</);
  assert.match(html, />Control de gasto</);
  assert.doesNotMatch(`${html}\n${script}\n${css}`, /shopify/i);
  assert.equal((script.match(/method\s*:\s*['"]POST['"]/gi) || []).length, 1);
  assert.match(script, /openid-connect\/token/);
  assert.doesNotMatch(script, /method\s*:\s*['"](?:PUT|PATCH|DELETE)['"]/i);
  assert.match(html, /Acciones ejecutadas: 0/);
  assert.match(html, /MODO SOLO LECTURA/);
  assert.match(html, /LA LÓGICA PRODUCTIVA NO SE MODIFICA/);
  assert.match(html, /ACCIONES EJECUTADAS: 0/);
  assert.match(html, /id="finance-view"/);
  assert.match(html, /fuente conciliada/);
  assert.match(script, /data\.costs/);
  assert.doesNotMatch(script, /costs\?\.total\s*\|\|\s*0/);
  assert.match(script, /lifecycle_status/);
  assert.match(script, /simulated_decision/);
  assert.match(script, /customer_replied_after_issue/);
  assert.match(script, /normalized_type/);
  assert.match(script, /response_evidence_status/);
  assert.match(script, /customer_intent_confidence/);
  assert.match(script, /effective_timer_status/);
  assert.match(script, /incidents\/overview/);
  assert.match(script, /queueController\?\.abort/);
  assert.match(script, /detailController\?\.abort/);
  assert.match(script, /state\.offset >= data\.total/);
  assert.match(script, /effective_decision_status/);
  assert.match(script, /dropea_freshness_status/);
  assert.match(script, /decision_status_reason/);
  assert.match(script, /translatedBlockers/);
  assert.match(script, /Propuesta condicionada/);
  assert.match(script, /Código GLS pendiente de gobernar/);
  assert.match(script, /Acción externa: no ejecutada \(NOT_EXECUTED\)/);
  assert.doesNotMatch(script, /\b(?:canonical_state|proposed_resolution|customer_response_status)\b/);
  assert.match(html, /<a id="login-button" class="primary-button" href="#" aria-disabled="true"/);
  assert.match(html, /id="login-notice"[^>]*role="alert"/);
  assert.match(html, /<link rel="stylesheet" href="login\.css\?v=20260808-hidden-fix-a00fe6d">/);
  assert.match(html, /<link rel="stylesheet" href="styles\.css\?v=20260815-incident-integrity-v2">/);
  assert.match(loginCss, /\[hidden\]\s*\{\s*display:\s*none\s*!important;/);
  assert.match(html, /<script src="app\.js\?v=20260815-incident-integrity-v2" defer><\/script>/);
  assert.match(html, /id="page-size"/);
  assert.match(html, /id="page-status"/);
  assert.match(script, /async function prepareLogin\(\)/);
  assert.match(script, /button\.href = url\.toString\(\)/);
  assert.match(script, /button\.setAttribute\('aria-disabled', 'false'\)/);
  assert.match(script, /if \(!state\.token\) \{ await prepareLogin\(\);/);
  assert.doesNotMatch(script, /login-button'\)\.addEventListener\('click'/);
  assert.match(script, /if \(params\.has\('error'\)\)/);
  assert.match(script, /refresh_interval_seconds/);
});

test('orders open on the pending dropshipper queue and expose Chatby intent', () => {
  const script = fs.readFileSync(new URL('./app.js', import.meta.url), 'utf8');
  assert.match(script, /filters: \{ lifecycle: 'PENDING' \}/);
  assert.match(script, /view === 'orders' \? \{ lifecycle: 'PENDING' \} : \{\}/);
  assert.match(script, /Pendientes de Dropshipper/);
  assert.match(script, /latest_customer_intent/);
});
